// Converts the bundled verified dataset into insert-only SQL seed statements.
// Usage: npm run db:seed
//
// Locations are inserted as drafts first, then published in a second pass so
// the database publish-gate trigger can verify the >= 5 photo rule.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dataset = JSON.parse(fs.readFileSync(path.join(root, "src/data/locations.generated.json"), "utf8"));

const q = (value) => {
  if (value === null || value === undefined) return "null";
  return `'${String(value).replace(/'/g, "''")}'`;
};
const json = (value) => `${q(JSON.stringify(value))}::jsonb`;
const arr = (values) =>
  values && values.length > 0 ? `array[${values.map((v) => q(v)).join(", ")}]::text[]` : "'{}'::text[]";

const out = [];
out.push("-- Generated by scripts/seed-locations.mjs — do not edit by hand.");
out.push(
  `-- Source dataset: ${dataset.meta.generated_at} · ${dataset.meta.published} published · ${dataset.meta.verified_photos} photos`,
);
out.push("begin;");
out.push("");

for (const loc of dataset.locations) {
  out.push("do $$");
  out.push("begin");
  out.push("insert into public.locations (");
  out.push("  id, slug, name_th, name_en, description_th, description_en, description_source,");
  out.push("  province_id, province, province_th, region, zone, district, address,");
  out.push("  latitude, longitude, coordinate_source, location_type, architectural_style,");
  out.push("  access_status, filming_permission_status, estimated_cost, contact_info, website_url, maps_url,");
  out.push("  verified_at, status, permission, filming, creative, tags, qid, commons_category, needs_admin_review");
  out.push(") values (");
  out.push(
    [
      q(loc.id),
      q(loc.slug),
      q(loc.name_th),
      q(loc.name_en),
      q(loc.description_th),
      q(loc.description_en),
      json(loc.description_source),
      q(loc.province_id),
      q(loc.province),
      q(loc.province_th),
      q(loc.region),
      q(loc.zone),
      q(loc.district),
      q(loc.address),
      String(loc.latitude),
      String(loc.longitude),
      json(loc.coordinate_source),
      q(loc.location_type),
      q(loc.architectural_style),
      q(loc.access_status),
      q(loc.filming_permission_status),
      q(loc.estimated_cost),
      q(loc.contact_info),
      q(loc.website_url),
      q(loc.maps_url),
      q(loc.verified_at),
      "'draft'",
      json(loc.permission),
      json(loc.filming),
      json(loc.creative),
      arr(loc.tags),
      q(loc.qid),
      q(loc.commons_category),
      String(Boolean(loc.needs_admin_review)),
    ].join(",\n  "),
  );
  out.push(") on conflict (id) do nothing;");
  out.push("if not found then return; end if;");
  out.push("");

  for (const photo of loc.photos) {
    out.push("insert into public.location_photos (");
    out.push("  id, location_id, title, image_url, thumb_url, original_url, source_name, source_page_url,");
    out.push("  photographer, credit, license, license_url, attribution_text, checksum, perceptual_hash,");
    out.push(
      "  width, height, is_cover, is_verified, verification_status, subject_evidence, verification_checks, retrieved_at",
    );
    out.push(") values (");
    out.push(
      [
        q(photo.id),
        q(loc.id),
        q(photo.title),
        q(photo.image_url),
        q(photo.thumb_url),
        q(photo.original_url),
        q(photo.source_name),
        q(photo.source_page_url),
        q(photo.photographer),
        q(photo.credit),
        q(photo.license),
        q(photo.license_url),
        q(photo.attribution_text),
        q(photo.checksum),
        q(photo.perceptual_hash),
        String(photo.width),
        String(photo.height),
        String(Boolean(photo.is_cover)),
        String(Boolean(photo.is_verified)),
        q(photo.verification_status),
        q(photo.subject_evidence),
        arr(photo.verification_checks),
        q(photo.retrieved_at),
      ].join(",\n  "),
    );
    out.push(");");
    out.push("");
  }

  for (const source of loc.sources) {
    out.push(
      `insert into public.location_sources (location_id, source_url, source_type, field_verified, checked_at) values (${q(
        loc.id,
      )}, ${q(source.source_url)}, ${q(source.source_type)}, ${q(source.field_verified)}, ${q(source.checked_at)});`,
    );
  }
  for (const category of loc.categories) {
    out.push(
      `insert into public.location_categories (location_id, category_slug) values (${q(loc.id)}, ${q(category)});`,
    );
  }
  for (const mood of loc.moods) {
    out.push(
      `insert into public.location_moods (location_id, mood_slug, relevance_score) values (${q(loc.id)}, ${q(
        mood.slug,
      )}, ${Math.round(mood.relevance_score * 100)});`,
    );
  }
  if (loc.status === "published") {
    out.push(
      `update public.locations set status = 'published', published_at = ${q(loc.published_at)} where id = ${q(loc.id)};`,
    );
  }
  out.push("end $$;", "");
}

out.push("commit;");

const outputPath = path.join(root, "supabase/seed/locations.sql");
fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, `${out.join("\n")}\n`, "utf8");

const published = dataset.locations.filter((l) => l.status === "published").length;
const photos = dataset.locations.reduce((n, l) => n + l.photos.length, 0);
console.log(`Wrote ${outputPath}: ${dataset.locations.length} locations (${published} published), ${photos} photos`);
